/**
 * Returns a fully localized scheme object for the given target language.
 * Falls back cleanly to English if a field or language translation is not available.
 */
export function getLocalizedScheme(scheme: Scheme, language: SupportedLanguage): Scheme {
  if (language === 'English') return scheme;

  const langData = SCHEME_TRANSLATIONS[language];
  const translated = langData ? langData[scheme.id] : undefined;

  const localizedCategory = getLocalizedCategory(scheme.category, language);

  if (!translated) {
    return {
      ...scheme,
      category: localizedCategory as SchemeCategory,
    };
  }

  return {
    ...scheme,
    category: (translated.category || localizedCategory) as SchemeCategory,
    benefit: translated.benefit || scheme.benefit,
    eligibility: translated.eligibility || scheme.eligibility,
    documents: translated.documents && translated.documents.length > 0 ? translated.documents : scheme.documents,
    summary: translated.summary || scheme.summary,
    purpose: translated.purpose || scheme.purpose,
    beneficiaries: translated.beneficiaries || scheme.beneficiaries,
    financialDetails: translated.financialDetails || scheme.financialDetails,
    howItWorks: translated.howItWorks || scheme.howItWorks,
    eligibilityCriteria: translated.eligibilityCriteria && translated.eligibilityCriteria.length > 0 ? translated.eligibilityCriteria : scheme.eligibilityCriteria,
    ineligibilityReasons: translated.ineligibilityReasons && translated.ineligibilityReasons.length > 0 ? translated.ineligibilityReasons : scheme.ineligibilityReasons,
    applicationSteps: translated.applicationSteps && translated.applicationSteps.length > 0 ? translated.applicationSteps : scheme.applicationSteps,
    offlineApplication: translated.offlineApplication || scheme.offlineApplication,
  };
}

/**
 * Translates a scheme category name (e.g. "Farmers" -> "ರೈತರು").
 */
export function getLocalizedCategory(category: string, language: SupportedLanguage): string {
  const table = CATEGORY_TRANSLATIONS[language] || CATEGORY_TRANSLATIONS.English;
  return table[category] || category;
}

/**
 * Translates eligibility evaluation status reasons.
 */
export function getLocalizedReason(reason: string, language: SupportedLanguage): string {
  const table = REASON_TRANSLATIONS[language] || REASON_TRANSLATIONS.English;
  return table[reason] || reason;
}
